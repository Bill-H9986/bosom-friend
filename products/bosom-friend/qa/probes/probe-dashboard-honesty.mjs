import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium } = require('C:/Users/Jay/Desktop/Bosom friend APP/node_modules/.pnpm/playwright-core@1.61.1/node_modules/playwright-core')
const BASE = process.env.BF_QA_BASE || 'http://127.0.0.1:31280/bosom-friend/'
const api = await (await fetch(BASE + 'api/v2/statistics/published-content-summary/dashboard')).json()
console.log('api metricAvailability=' + JSON.stringify(api?.data?.metricAvailability))
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto(BASE + '?planId=mg-persist&_r=' + Date.now() + '#/data-statistics', { waitUntil: 'domcontentloaded' })
