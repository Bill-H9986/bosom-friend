await views.click({ timeout: 8000 }).catch(error => console.log('click error: ' + String(error).slice(0, 120)))
await page.waitForTimeout(2000)
console.log('notices-after=' + await page.locator('[data-testid=data-statistics-metric-unavailable]').count())
