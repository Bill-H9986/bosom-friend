/**
 * 把更新记录转成通知中心的条目。
 *
 * @returns 与前端 `NotificationItem` 对齐的更新日志条目（最新在前）。
 */
export function changelogNotifications(): Array<{
  id: string
  type: 'changelog'
  title: string
  content: string
  time: string
}> {
  return PRODUCT_CHANGELOG.map(entry => ({
    id: 'changelog-' + entry.version,
    type: 'changelog' as const,
    title: 'v' + entry.version + '｜' + entry.title,
    content: entry.items.map(item => '· ' + item).join('\n'),
    time: entry.date,
  }))
}
